#!/usr/bin/env node
// refreshes src/snapshot.ts from the live server (block 492): the tools and
// instructions cuehq-mcp serves to tools/list when it runs without a key.
//   CUEHQ_API_KEY=cuehq_sk_… npm run snapshot
// npm builds first (presnapshot), so the endpoint rule is dist/url-rule.js,
// the code the command itself runs: the key goes only where the command would
// send it. CUEHQ_MCP_URL (optional) names another endpoint under that rule.
// the file holds the server's instructions and tool list and nothing else:
// no key, no account data. an empty tool list is refused, never written.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { Client, StreamableHTTPClientTransport } from '@modelcontextprotocol/client';
// the rule comes from the build, so a direct `node scripts/snapshot.mjs` on a
// tree without dist/ says what to run instead of a module-resolution error.
const { endpointFromEnv, URL_RULE } = await import('../dist/url-rule.js').catch(() => {
  process.stderr.write('snapshot: dist/url-rule.js is missing; run `npm run snapshot` (it builds first).\n');
  process.exit(1);
});

const key = (process.env.CUEHQ_API_KEY ?? '').trim();
if (!/^cuehq_sk_[0-9A-Za-z]{32}$/.test(key)) {
  process.stderr.write('snapshot: set CUEHQ_API_KEY to a key from CueHQ settings, agents (cuehq_sk_…).\n');
  process.exit(1);
}
const url = endpointFromEnv(process.env.CUEHQ_MCP_URL);
if (!url) {
  process.stderr.write(`snapshot: ${URL_RULE}\n`);
  process.exit(1);
}
const client = new Client({ name: 'cuehq-mcp-snapshot', version: '0.0.0' });
await client.connect(new StreamableHTTPClientTransport(url, { requestInit: { headers: { Authorization: `Bearer ${key}` } } }));
const { tools } = await client.listTools();
const instructions = client.getInstructions() ?? '';
await client.close();
if (!Array.isArray(tools) || tools.length === 0) {
  process.stderr.write('snapshot: the server listed no tools; nothing written.\n');
  process.exit(1);
}

const snapshot = { generatedAt: new Date().toISOString(), instructions, tools };
const text = `// generated by \`npm run snapshot\` on ${snapshot.generatedAt}: the live server's
// instructions and tools (name, title, description, input schema, annotations),
// what \`cuehq-mcp\` serves to tools/list when it runs without a key (block 492).
// do not edit by hand; refresh with CUEHQ_API_KEY set.
import type { Client } from '@modelcontextprotocol/client';

export type SnapshotTools = Awaited<ReturnType<Client['listTools']>>['tools'];
export interface Snapshot {
  generatedAt: string;
  instructions: string;
  tools: SnapshotTools;
}

export const SNAPSHOT: Snapshot = ${JSON.stringify(snapshot, null, 2)};
`;
writeFileSync(fileURLToPath(new URL('../src/snapshot.ts', import.meta.url)), text);
process.stderr.write(`snapshot: ${tools.length} tools and ${instructions.length} characters of instructions from ${url.href}, written to src/snapshot.ts\n`);
